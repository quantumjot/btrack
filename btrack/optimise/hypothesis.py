from btrack import constants

from dataclasses import dataclass
from typing import ClassVar

H_TYPES = [
    "P_FP",
    "P_init",
    "P_term",
    "P_link",
    "P_branch",
    "P_dead",
    "P_merge",
]


@dataclass
class Hypothesis:
    """Hypothesis structure.

    These are automatically generated by the optimiser.
    """

    hypothesis: int = 0
    ID: int = 0
    probability: float = 0.0
    link_ID: int = 0
    child_one_ID: int = 0
    child_two_ID: int = 0
    parent_one_ID: int = 0
    parent_two_ID: int = 0

    _fields_: ClassVar[list] = [
        ("hypothesis", int),
        ("ID", int),
        ("probability", float),
        ("link_ID", int),
        ("child_one_ID", int),
        ("child_two_ID", int),
        ("parent_one_ID", int),
        ("parent_two_ID", int),
    ]

    @property
    def hypothesis_type(self) -> constants.Fates:
        return constants.Fates(self.hypothesis)

    @property
    def log_likelihood(self) -> float:
        return self.probability


@dataclass
class PyHypothesisParams:
    """HypothesisParams.

    A convenient way to send hypothesis generation parameters to the hypothesis
    engine.
    """

    lambda_time: float = 0.0
    lambda_dist: float = 0.0
    lambda_link: float = 0.0
    lambda_branch: float = 0.0
    eta: float = 1e-10
    theta_dist: float = 0.0
    theta_time: float = 0.0
    dist_thresh: float = 0.0
    time_thresh: float = 0.0
    apop_thresh: int = 0
    segmentation_miss_rate: float = 0.0
    apoptosis_rate: float = 0.0
    relax: bool = False
    hypotheses_to_generate: int = 0

    _fields_: ClassVar[list] = [
        ("lambda_time", float),
        ("lambda_dist", float),
        ("lambda_link", float),
        ("lambda_branch", float),
        ("eta", float),
        ("theta_dist", float),
        ("theta_time", float),
        ("dist_thresh", float),
        ("time_thresh", float),
        ("apop_thresh", int),
        ("segmentation_miss_rate", float),
        ("apoptosis_rate", float),
        ("relax", bool),
        ("hypotheses_to_generate", int),
    ]
